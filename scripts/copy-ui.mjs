#!/usr/bin/env node
/**
 * 把 gateway/ui 拷进 <壳>/src-tauri/ui/，打进包。桌面端和手机端的 `prepare:ui` 都走这一份：
 *
 *   node ../scripts/copy-ui.mjs desktop   # 壳子用 satu:// 协议从这儿发界面（desktop ui.rs 的 serve_ui）
 *   node ../scripts/copy-ui.mjs mobile    # 作为 frontendDist 打进手机包（mobile lib.rs 的 serve_ui 从 asset_resolver 里发）
 *
 * 开发时（tauri dev / tauri ios dev）不用拷——壳子直接读仓库里的 gateway/ui。
 */
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const shell = process.argv[2]
if (shell !== 'desktop' && shell !== 'mobile') {
  console.error('copy-ui: 用法 node scripts/copy-ui.mjs desktop|mobile')
  process.exit(1)
}
const root = dirname(dirname(fileURLToPath(import.meta.url)))
const out = process.env.SATUWORK_UI_OUT || join(root, shell, 'src-tauri', 'ui')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
// 拷完 gateway/ui 再补占位 README，和 runtime/ 一样让 tauri-build 的通配永远有东西可命中。
cpSync(join(root, 'gateway', 'ui'), out, { recursive: true })
writeFileSync(join(out, 'README.txt'), `Generated by \`pnpm --filter satuwork-${shell} prepare:ui\` before packaging. Source: gateway/ui.\n`)
console.log(`${shell}: 界面已拷到 ${out}`)

if (shell === 'desktop' && process.env.SATUWORK_BUNDLE_UI_LIBS === '1') {
  const { bundleUiLibs } = await import('./bundle-ui-libs.mjs')
  await bundleUiLibs(out)
}
