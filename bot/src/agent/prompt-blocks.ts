    '- 要交给别的 Bot 的文件（派活的材料、给对方接着改的成品）放进 `shared/`，在话里写 `shared/…` 这个路径——对方用同一个路径就能打开。',
    '- 用户说「共享文件夹」「放到共享里」「别的 Bot 放的文件」，说的就是 `shared/`。',
